  private static let exportSource = #"""
  """Convert one trained Pixeltje checkpoint to a Core AI inference asset."""
  import argparse
  import asyncio
  import shutil
  import uuid
  from pathlib import Path

  import numpy as np
  import torch
  from coreai_torch import TorchConverter, get_decomp_table

  from model import GRAPH_SHA256, IMAGE_SHAPE, OUTPUT_NAME, build_model


  async def main():
      parser = argparse.ArgumentParser(description=__doc__)
      parser.add_argument("--checkpoint", type=Path, required=True)
      parser.add_argument("--output", type=Path, required=True)
      parser.add_argument("--atol", type=float, default=0.02)
      args = parser.parse_args()
      if args.output.exists():
          parser.error("Output already exists; choose a new .aimodel path")
      if args.atol <= 0:
          parser.error("Tolerance must be positive")
      checkpoint = torch.load(args.checkpoint, map_location="cpu", weights_only=True)
      if checkpoint["graph_sha256"] != GRAPH_SHA256:
          raise ValueError("Checkpoint belongs to another model design")
      model = build_model().eval()
      model.load_state_dict(checkpoint["model_state_dict"], strict=True)
      sample = torch.linspace(0, 1, int(np.prod(IMAGE_SHAPE)), dtype=torch.float32)
      sample = sample.reshape((1, *IMAGE_SHAPE))
      with torch.no_grad():
          reference = model(sample).numpy()
      if not np.isfinite(reference).all():
          raise RuntimeError("PyTorch reference output is nonfinite")
      program = torch.export.export(model, args=(sample,)).run_decompositions(get_decomp_table())
      converter = TorchConverter(mode=TorchConverter.Mode.RELEASE)
      converter.add_exported_program(program, input_names=["image"], output_names=[OUTPUT_NAME])
      asset = converter.to_coreai()
      asset.optimize()
      args.output.parent.mkdir(parents=True, exist_ok=True)
      temporary = args.output.with_name(f".{args.output.name}.{uuid.uuid4().hex}.staging.aimodel")
      try:
          asset.save_asset(temporary)
          from coreai.runtime import AIModel, NDArray, SpecializationOptions, ComputeUnitKind
          options = SpecializationOptions.from_preferred_compute_unit_kind(ComputeUnitKind.gpu())
          loaded = await AIModel.load(temporary, options)
          function = loaded.load_function("main")
          actual = (await function({"image": NDArray(sample.numpy())}))[OUTPUT_NAME].numpy()
          if actual.shape != reference.shape or not np.isfinite(actual).all():
              raise RuntimeError("Core AI output has the wrong shape or nonfinite values")
          difference = float(np.max(np.abs(actual.astype(np.float32) - reference)))
          print(f"Core AI max absolute difference: {difference:.6f}")
          if difference > args.atol:
              raise RuntimeError(f"Core AI parity exceeded tolerance {args.atol}")
          if args.output.exists():
              raise FileExistsError(args.output)
          temporary.rename(args.output)
      finally:
          if temporary.exists():
              shutil.rmtree(temporary)


  if __name__ == "__main__":
      asyncio.run(main())
