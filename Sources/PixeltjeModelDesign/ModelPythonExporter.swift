public enum ModelExportError: Error, LocalizedError {
  case invalid([ModelIssue])
  case destinationExists

  public var errorDescription: String? {
    switch self {
    case .invalid(let issues): issues.map(\.message).joined(separator: "\n")
    case .destinationExists: "The export destination already exists. Choose a new folder."
    }
  }
}

public enum ModelPythonExporter {
  public static func export(
    _ document: ModelDesignDocument, workflow: PipelineDocument, to destination: URL
  ) throws {
    let report = ModelDesignValidator.validate(document)
    guard report.isValid else { throw ModelExportError.invalid(report.issues) }
    guard !FileManager.default.fileExists(atPath: destination.path) else {
      throw ModelExportError.destinationExists
    }
    let model = try modelSource(document, report: report)
    let folder = destination.deletingLastPathComponent()
    let staging = folder.appendingPathComponent(".\(destination.lastPathComponent).\(UUID().uuidString).tmp")
    try FileManager.default.createDirectory(at: staging, withIntermediateDirectories: true)
    do {
      try model.write(to: staging.appendingPathComponent("model.py"), atomically: true, encoding: .utf8)
      let source = document.training.resolvedTask == .classification
        ? ModelPythonClassification.trainingSource : trainSource
      let training = source
        .replacingOccurrences(of: "DEFAULT_EPOCHS", with: String(document.training.epochs))
        .replacingOccurrences(of: "DEFAULT_BATCH_SIZE", with: String(document.training.batchSize))
        .replacingOccurrences(of: "DEFAULT_LEARNING_RATE", with: String(document.training.learningRate))
        .replacingOccurrences(of: "DEFAULT_SEED", with: String(document.training.seed))
        .replacingOccurrences(of: "DEFAULT_DATASET_PRESET",
          with: document.training.datasetPreset?.rawValue ?? "none")
      try training.write(to: staging.appendingPathComponent("train.py"), atomically: true, encoding: .utf8)
      try exportSource.write(to: staging.appendingPathComponent("export_coreai.py"), atomically: true, encoding: .utf8)
      let readme = document.training.resolvedTask == .classification
        ? ModelPythonClassification.readmeSource : readmeSource
      try readme.write(to: staging.appendingPathComponent("README.md"), atomically: true, encoding: .utf8)
      try PipelineJSON.encode(workflow).write(
        to: staging.appendingPathComponent("workflow.pixpipeline.json"))
      try FileManager.default.moveItem(at: staging, to: destination)
    } catch {
      try? FileManager.default.removeItem(at: staging)
      throw error
    }
  }

  public static func modelSource(
    _ document: ModelDesignDocument, report: ModelValidationReport? = nil
  ) throws -> String {
    let report = report ?? ModelDesignValidator.validate(document)
    guard report.isValid else { throw ModelExportError.invalid(report.issues) }
    let hash = try ModelDesignJSON.architectureSHA256(document)
    let nodes = Dictionary(uniqueKeysWithValues: document.nodes.map { ($0.id, $0) })
    let incoming = Dictionary(grouping: document.edges, by: \.target)
    let inputNode = document.nodes.first { $0.kind == .input }!
    let outputNode = document.nodes.first { $0.kind == .output }!
    func variable(_ id: UUID) -> String { "v_" + id.uuidString.replacingOccurrences(of: "-", with: "").lowercased() }
    func module(_ id: UUID) -> String { "m_" + id.uuidString.replacingOccurrences(of: "-", with: "").lowercased() }
    func predecessor(_ node: ModelNode, port: String) -> UUID {
      incoming[node.id]!.first { $0.input == port }!.source
    }
    let nameLiteral = try pythonString(document.name)
    var lines = [
      "# Generated by Pixeltje Pipeline. Edit the workflow and export again.",
      "import torch",
      "from torch import nn",
      "",
      "GRAPH_SHA256 = \"\(hash)\"",
      "MODEL_NAME = \(nameLiteral)",
      "IMAGE_SHAPE = (\(inputNode.shape.map(String.init).joined(separator: ", ")))\(inputNode.shape.count == 1 ? "," : "")",
      "OUTPUT_SHAPE = (\(report.shapes[outputNode.id]!.map(String.init).joined(separator: ", ")))\(report.shapes[outputNode.id]!.count == 1 ? "," : "")",
      "OUTPUT_NAME = \"\(document.training.resolvedTask == .classification ? "scores" : "image")\"",
      "",
      "class Model(nn.Module):",
      "    def __init__(self):",
      "        super().__init__()",
    ]
    let layers = report.orderedNodeIDs.compactMap { nodes[$0] }.filter { $0.kind == .layer }
    if layers.isEmpty { lines.append("        pass") }
    for node in layers {
      let inputShape = report.shapes[predecessor(node, port: "input")]!
      let expression: String
      switch node.layer! {
      case .conv2d:
        expression = "nn.Conv2d(\(inputShape[0]), \(node.units), \(node.kernelSize), padding=\(node.kernelSize / 2))"
      case .relu: expression = "nn.ReLU()"
      case .dense: expression = "nn.Linear(\(inputShape[0]), \(node.units))"
      case .flatten: expression = "nn.Flatten()"
      }
      lines.append("        self.\(module(node.id)) = \(expression)")
    }
    lines += ["", "    def forward(self, image):"]
    for id in report.orderedNodeIDs {
      guard let node = nodes[id] else { continue }
      let expression: String
      switch node.kind {
      case .input: expression = "image"
      case .layer: expression = "self.\(module(id))(\(variable(predecessor(node, port: "input"))))"
      case .merge:
        let left = variable(predecessor(node, port: "left"))
        let right = variable(predecessor(node, port: "right"))
        switch node.merge! {
        case .add: expression = "\(left) + \(right)"
        case .concatenate: expression = "torch.cat((\(left), \(right)), dim=\(node.axis + 1))"
        }
      case .output: expression = variable(predecessor(node, port: "input"))
      }
      lines.append("        \(variable(id)) = \(expression)")
    }
    lines += [
      "        return \(variable(outputNode.id))",
      "",
      "def build_model():",
      "    return Model()",
      "",
      "if __name__ == \"__main__\":",
      "    model = build_model().eval()",
      "    sample = torch.zeros((1, *IMAGE_SHAPE), dtype=torch.float32)",
      "    with torch.no_grad():",
      "        print(MODEL_NAME, GRAPH_SHA256, tuple(model(sample).shape))",
      "    print(model)",
      "",
    ]
    return lines.joined(separator: "\n")
  }

  private static func pythonString(_ value: String) throws -> String {
    let data = try JSONEncoder().encode(value)
    return String(decoding: data, as: UTF8.self)
  }

  private static let trainSource = #"""
  """Train a Pixeltje model from paired float32 NCHW image arrays."""
  import argparse
  import json
  import os
  from pathlib import Path

  import numpy as np
  import torch
  from torch.utils.data import DataLoader, TensorDataset, random_split

  from model import GRAPH_SHA256, IMAGE_SHAPE, build_model


  def load_pairs(path: Path | None, count: int, seed: int):
      if path is None:
          generator = torch.Generator().manual_seed(seed)
          target = torch.rand((count, *IMAGE_SHAPE), generator=generator)
          source = (target + 0.15 * torch.randn(target.shape, generator=generator)).clamp(0, 1)
          return source, target
      with np.load(path, allow_pickle=False) as arrays:
          source = np.asarray(arrays["inputs"], dtype=np.float32)
          target = np.asarray(arrays["targets"], dtype=np.float32)
      expected = (None, *IMAGE_SHAPE)
      if source.ndim != len(expected) or source.shape[1:] != IMAGE_SHAPE or target.shape != source.shape:
          raise ValueError(f"Expected matching NCHW arrays with trailing shape {IMAGE_SHAPE}")
      if len(source) < 2 or not np.isfinite(source).all() or not np.isfinite(target).all():
          raise ValueError("Dataset needs at least two finite input/target pairs")
      if source.min() < 0 or source.max() > 1 or target.min() < 0 or target.max() > 1:
          raise ValueError("Image tensors must be normalized to [0, 1]")
      return torch.from_numpy(source), torch.from_numpy(target)


  def main():
      parser = argparse.ArgumentParser(description=__doc__)
      parser.add_argument("--data", type=Path, help="NPZ with inputs and targets arrays; omit for a synthetic smoke run")
      parser.add_argument("--output-dir", type=Path, required=True)
      parser.add_argument("--epochs", type=int, default=DEFAULT_EPOCHS)
      parser.add_argument("--batch-size", type=int, default=DEFAULT_BATCH_SIZE)
      parser.add_argument("--learning-rate", type=float, default=DEFAULT_LEARNING_RATE)
      parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
      parser.add_argument("--resume", type=Path)
      args = parser.parse_args()
      if args.epochs < 1 or args.batch_size < 1 or args.learning_rate <= 0:
          parser.error("epochs, batch size, and learning rate must be positive")
      torch.manual_seed(args.seed)
      source, target = load_pairs(args.data, 32, args.seed)
      device = torch.device("mps" if torch.backends.mps.is_available() else "cpu")
      model = build_model().to(device)
      optimizer = torch.optim.Adam(model.parameters(), lr=args.learning_rate)
      start_epoch = 0
      if args.resume:
          checkpoint = torch.load(args.resume, map_location="cpu", weights_only=True)
          if checkpoint["graph_sha256"] != GRAPH_SHA256:
              raise ValueError("Checkpoint belongs to another model design")
          model.load_state_dict(checkpoint["model_state_dict"], strict=True)
          optimizer.load_state_dict(checkpoint["optimizer_state_dict"])
          start_epoch = int(checkpoint["epoch"])
      dataset = TensorDataset(source, target)
      validation_count = max(1, len(dataset) // 5)
      training_count = len(dataset) - validation_count
      train_set, validation_set = random_split(
          dataset, [training_count, validation_count],
          generator=torch.Generator().manual_seed(args.seed))
      loader = DataLoader(train_set, batch_size=args.batch_size, shuffle=True)
      validation_loader = DataLoader(validation_set, batch_size=args.batch_size)
      args.output_dir.mkdir(parents=True, exist_ok=True)
      for epoch in range(start_epoch, args.epochs):
          model.train()
          total = 0.0
          for x, y in loader:
              x, y = x.to(device), y.to(device)
              optimizer.zero_grad(set_to_none=True)
              loss = torch.nn.functional.mse_loss(model(x), y)
              loss.backward()
              optimizer.step()
              total += float(loss.detach().cpu()) * len(x)
          mean_loss = total / training_count
          model.eval()
          validation_total = 0.0
          with torch.no_grad():
              for x, y in validation_loader:
                  x, y = x.to(device), y.to(device)
                  validation_total += float(torch.nn.functional.mse_loss(model(x), y).cpu()) * len(x)
          validation_loss = validation_total / validation_count
          checkpoint = {"epoch": epoch + 1, "graph_sha256": GRAPH_SHA256,
                        "model_state_dict": model.state_dict(),
                        "optimizer_state_dict": optimizer.state_dict(),
                        "validation_loss": validation_loss}
          temporary = args.output_dir / "checkpoint.tmp"
          torch.save(checkpoint, temporary)
          os.replace(temporary, args.output_dir / "checkpoint.pt")
          print(json.dumps({"epoch": epoch + 1, "epochs": args.epochs,
                            "loss": mean_loss, "validation_loss": validation_loss,
                            "device": str(device)}), flush=True)


  if __name__ == "__main__":
      main()
